import 'dart:io';

import 'package:flutter/material.dart' show Icons;
import 'package:flutter_test/flutter_test.dart';
import 'package:interior_design_recommendation/features/customer/ar/data/catalog_model_resolver.dart';
import 'package:interior_design_recommendation/features/customer/ar/data/glb_bounds.dart';
import 'package:interior_design_recommendation/features/customer/scanner/data/furniture_catalog.dart';

void main() {
  late Directory tempRoot;

  setUp(() {
    tempRoot = Directory.systemTemp.createTempSync('catalog_models_test_');
  });

  tearDown(() {
    try {
      tempRoot.deleteSync(recursive: true);
    } catch (_) {}
  });

  CatalogModelResolver resolver() =>
      CatalogModelResolver(cacheRootProvider: () async => tempRoot);

  RoomCatalogItem item(String iconName) =>
      roomCatalog.firstWhere((c) => c.iconName == iconName);

  test('bundled pieces resolve to their asset URI', () async {
    final src = await resolver().resolve(item('sofa'));
    expect(src.sourceType, 'asset');
    expect(src.source, 'assets/models/three_seater_sofa.glb');
  });

  test('stand-in pieces generate a real model at catalog size', () async {
    final src = await resolver().resolve(item('rug'));
    expect(src.sourceType, 'file');
    expect(src.file!.existsSync(), isTrue);
    final b = GlbBounds.fromGlbBytes(src.file!.readAsBytesSync());
    expect(b.widthM, closeTo(1.6, 0.02), reason: '160 cm wide');
    expect(b.depthM, closeTo(1.2, 0.02), reason: '120 cm deep');
    expect(b.heightM, closeTo(0.02, 0.01), reason: 'rug is a 2 cm mat');
    expect(b.minY, closeTo(0, 1e-6));
  });

  test('cabinet generates at true catalog height', () async {
    final src = await resolver().resolve(item('cabinet'));
    expect(src.sourceType, 'file');
    final b = GlbBounds.fromGlbBytes(src.file!.readAsBytesSync());
    expect(b.heightM, closeTo(1.8, 0.02), reason: '180 cm tall');
    expect(b.widthM, closeTo(0.9, 0.02));
    expect(b.depthM, closeTo(0.5, 0.02));
  });

  test('an unknown icon generates instead of borrowing a bundled shape',
      () async {
    const mystery = RoomCatalogItem(
        'Mystery Block', 'mystery_block', Icons.interests, 'misc', 120, 30,
        null, 45);
    final src = await resolver().resolve(mystery);
    expect(src.sourceType, 'file');
    final b = GlbBounds.fromGlbBytes(src.file!.readAsBytesSync());
    expect(b.widthM, closeTo(1.2, 0.02), reason: '120 cm wide');
    expect(b.heightM, closeTo(0.45, 0.02), reason: '45 cm tall');
    expect(b.depthM, closeTo(0.3, 0.02), reason: '30 cm deep');
    expect(b.minY, closeTo(0, 1e-6));
  });

  test('second resolve is a cache hit', () async {
    final r = resolver();
    final first = await r.resolve(item('bookshelf'));
    final before = first.file!.statSync().modified;
    final second = await r.resolve(item('bookshelf'));
    expect(second.file!.path, first.file!.path);
    expect(second.file!.statSync().modified, before);
  });

  test('generated bytes are deterministic across resolvers', () async {
    final a = await resolver().resolve(item('tv_stand'));
    final b = await resolver().resolve(item('tv_stand'));
    expect(a.file!.readAsBytesSync(), b.file!.readAsBytesSync());
  });

  test('every stand-in icon resolves to a parseable GLB', () async {
    for (final iconName in kGeneratedCatalogIcons) {
      final src = await resolver().resolve(item(iconName));
      expect(src.sourceType, 'file', reason: iconName);
      final b = GlbBounds.fromGlbBytes(src.file!.readAsBytesSync());
      expect(b.widthM, greaterThan(0), reason: iconName);
      expect(b.heightM, greaterThan(0), reason: iconName);
    }
  });
}
